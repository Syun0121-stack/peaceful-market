// Run after loading Ground Zero in a clean Mindustry v160.7 headless instance.
// Console: js Vars.world.loadSector(SectorPresets.groundZero.sector);
// Then: js eval(Core.files.absolute('/absolute/path/tests/headless.js').readString());
(function(){
    var checks = 0;
    function check(value, message){ if(!value) throw new Error(message); checks++; print('PASS ' + message); }
    var m = Vars.content.block('peaceful-market-market');
    var coin = Vars.content.item('peaceful-market-credit');
    var r = Vars.state.rules, c = r.defaultTeam.core();
    var ek = 'peaceful-market-earned-v1', tk = 'peaceful-market-tutorial-v1';
    function pulse(){ Events.fire(Trigger.update); }
    Vars.state.set(Packages.mindustry.core.GameState.State.playing);
    r.tags.put(ek, '0'); r.tags.put(tk, '0'); r.tags.put('peaceful-market-goal-v1', 'false');
    Vars.state.getSector().info.wasCaptured = false;
    c.items.clear();
    check(m.hasBuilding(), 'market creates a Building through Tile.setBlock');
    check(!r.waves && !r.waveTimer && r.disableWorldProcessors, 'combat and original tutorial processor disabled');
    check(!r.objectives.any(), 'original map objectives removed');
    pulse();
    check(String(r.mission).indexOf('1/4') >= 0, 'tutorial starts at resource collection');
    c.items.add(Items.copper,35); c.items.add(Items.lead,20); pulse();
    check(String(r.mission).indexOf('2/4') >= 0, 'tutorial advances to market construction');
    var x = c.tileX()+8, y = c.tileY();
    Vars.world.tile(x,y).setBlock(m,Team.sharded,0);
    var b = Vars.world.tile(x,y).build;
    check(b !== null && b.team === Team.sharded, 'placed market exists with correct team');
    pulse();
    check(String(r.mission).indexOf('3/4') >= 0, 'tutorial advances to conveyor connection');
    Vars.world.tile(x-1,y).setBlock(Blocks.conveyor,Team.sharded,0);
    var belt = Vars.world.tile(x-1,y).build;
    check(belt.front() === b, 'real conveyor points into market');
    belt.handleItem(c, Items.copper);
    Time.delta = 1;
    for(var i = 0; i < 120; i++) belt.update();
    check(c.items.get(coin) > 0 && belt.items.total() === 0, 'conveyor transfers resource and credits core');
    pulse();
    check(String(r.mission).indexOf('4/4') >= 0, 'first sale advances tutorial to earnings goal');
    var unit = UnitTypes.alpha.create(Team.sharded);
    check(b.acceptStack(Items.copper,5,unit) === 5, 'manual unit stack accepted');
    var before = c.items.get(coin);
    b.handleStack(Items.copper,5,unit);
    check(c.items.get(coin) > before, 'manual unit stack sold');
    check(!b.acceptItem(c,coin) && b.acceptStack(coin,10,unit) === 0, 'credits cannot be resold');
    var enemy = UnitTypes.alpha.create(Team.crux);
    check(b.acceptStack(Items.copper,10,enemy) === 0, 'enemy stack rejected');
    before = c.items.get(coin); b.handleStack(Items.copper,10,enemy);
    check(c.items.get(coin) === before, 'enemy handler cannot create credits');
    c.items.set(coin,c.storageCapacity);
    check(!b.acceptItem(c,Items.copper) && b.acceptStack(Items.lead,50,unit) === 0, 'full core blocks all input');
    b.handleStack(Items.copper,10,unit);
    check(c.items.get(coin) === c.storageCapacity, 'handler cannot overflow full core');
    c.items.set(coin,c.storageCapacity-3);
    var n = b.acceptStack(Items.copper,100,unit);
    check(n > 0 && n <= 3, 'partial stack limited by credit capacity');
    b.handleStack(Items.copper,n,unit);
    check(c.items.get(coin) <= c.storageCapacity, 'partial sale stays within capacity');
    var total = Number(r.tags.get(ek));
    c.items.set(coin,0); pulse();
    check(Number(r.tags.get(ek)) === total, 'spending does not reduce earned credits');
    b.handleStack(Items.copper,500,unit); pulse();
    check(r.tags.get('peaceful-market-goal-v1') === 'true', 'cumulative earnings complete regional goal');
    check(Vars.state.getSector().info.wasCaptured, 'credit goal captures region through engine');
    check(String(r.mission).indexOf('경제 튜토리얼 완료') >= 0, 'tutorial completion displayed');
    check(!r.waves && !r.waveTimer, 'capture does not re-enable waves');
    var file = Core.files.local('economy-regression.msav');
    Packages.mindustry.io.SaveIO.write(file);
    var savedTotal = r.tags.get(ek);
    Packages.mindustry.io.SaveIO.load(file);
    check(Vars.state.rules.tags.get(ek) === savedTotal, 'earned credits survive save/load');
    check(Vars.state.rules.tags.get(tk) === '4', 'tutorial progress survives save/load');
    check(Vars.world.tile(x,y).build !== null, 'placed market survives save/load');
    check(Vars.world.tile(x,y).build.acceptItem(null,Items.copper), 'loaded market still accepts resources');
    var oldSector = Vars.state.rules.sector;
    Vars.state.rules.sector = null;
    check(!Vars.world.tile(x,y).build.acceptItem(null,Items.copper), 'non-campaign input rejected');
    Vars.state.rules.sector = oldSector;
    print('ALL ' + checks + ' CHECKS PASSED');
})();
